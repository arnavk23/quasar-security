"""
Enterprise-network flow generator.

Individual NetFlow/IPFIX records are not simulated packet-by-packet; instead,
each flow is represented directly as a d-dimensional feature vector whose
marginal distributions are calibrated to match commonly reported NetFlow
aggregate statistics (Pareto packet rates, lognormal byte rates, Weibull flow
durations, Zipf-like port concentration), combined via a Gaussian copula so
that features within a semantic group (header / flow / behavioral) are
correlated the way real flow statistics are. This is a standard simplification
for synthetic IDS benchmarking (cf. the marginal-plus-copula approach used to
build CICIDS-style synthetic extensions) and is documented here explicitly
rather than presented as packet-level simulation.

Attack traffic is generated by shifting and inflating the variance of a fixed,
attack-specific subset of feature dimensions in the copula's latent Gaussian
space before applying the marginal transform. This keeps the same marginal
family (so attacks don't trivially stick out as out-of-range values) while
creating a class-conditional signature whose strength is controlled by
``attack_strength``.
"""

import numpy as np
import pandas as pd
from scipy import stats

_MARGINAL_CYCLES = {
    "header": [
        ("beta", dict(a=2.0, b=5.0)),
        ("gamma", dict(a=2.0, scale=1.0)),
        ("lognormal", dict(s=0.8, scale=np.exp(0.5))),
        ("normal", dict()),
    ],
    "flow": [
        ("pareto", dict(b=2.1)),
        ("lognormal", dict(s=1.8, scale=np.exp(6.2))),
        ("weibull", dict(c=0.7, scale=15.3)),
        ("normal", dict()),
    ],
    "behavioral": [
        ("beta", dict(a=1.5, b=3.0)),
        ("gamma", dict(a=1.5, scale=1.0)),
        ("lognormal", dict(s=1.0, scale=np.exp(0.3))),
        ("normal", dict()),
    ],
}

# Fixed, documented attack -> perturbed-dimension mapping, expressed as
# (group, fractional position within group) so it resolves correctly for any
# n_header/n_flow/n_behavioral split (used by the dimensionality sweep).
_ATTACK_GROUP_FRACTIONS = {
    # port scan: header (SYN/ACK/RST ratio, port entropy) + short flow duration
    "port_scan": [("header", 0.05), ("header", 0.25), ("header", 0.45), ("header", 0.65),
                  ("header", 0.85), ("flow", 0.05), ("flow", 0.15)],
    # ddos: volumetric flow features (pkts/sec, pkt size, src entropy) + protocol dist.
    "ddos": [("header", 0.90), ("flow", 0.20), ("flow", 0.35), ("flow", 0.50),
             ("flow", 0.65), ("flow", 0.80), ("flow", 0.95)],
    # exfiltration: outbound behavioral entropy + bytes/sec
    "exfiltration": [("flow", 0.85), ("flow", 0.95), ("behavioral", 0.05),
                      ("behavioral", 0.15), ("behavioral", 0.25), ("behavioral", 0.35)],
    # dns tunneling: shares outbound-behavioral dims with exfiltration (realistic
    # confusion between the two, matching Section 5.1's discussion) + query-rate-like flow dims
    "dns_tunneling": [("flow", 0.90), ("flow", 0.98), ("behavioral", 0.20),
                       ("behavioral", 0.30), ("behavioral", 0.40), ("behavioral", 0.50)],
    # arp spoofing: header MAC/IP-binding dims + behavioral gateway-reachability/MAC-flux dims
    "arp_spoofing": [("header", 0.40), ("header", 0.55), ("header", 0.70),
                      ("behavioral", 0.70), ("behavioral", 0.80), ("behavioral", 0.90)],
}


def _resolve_attack_dims(n_header: int, n_flow: int, n_behavioral: int) -> dict:
    bounds = {
        "header": (0, n_header),
        "flow": (n_header, n_header + n_flow),
        "behavioral": (n_header + n_flow, n_header + n_flow + n_behavioral),
    }
    resolved = {}
    for atk, items in _ATTACK_GROUP_FRACTIONS.items():
        idx = set()
        for group, frac in items:
            lo, hi = bounds[group]
            width = max(hi - lo, 1)
            idx.add(min(lo + int(round(frac * (width - 1))), hi - 1))
        resolved[atk] = sorted(idx)
    return resolved


def _build_marginals(n_header: int, n_flow: int, n_behavioral: int, rng: np.random.Generator):
    marginals = []
    for group, n in (("header", n_header), ("flow", n_flow), ("behavioral", n_behavioral)):
        cycle = _MARGINAL_CYCLES[group]
        for i in range(n):
            name, params = cycle[i % len(cycle)]
            jitter = {k: v * rng.uniform(0.85, 1.15) for k, v in params.items()}
            marginals.append((name, jitter))
    return marginals


def _sample_marginal(name: str, params: dict, u: np.ndarray) -> np.ndarray:
    u = np.clip(u, 1e-6, 1 - 1e-6)
    if name == "beta":
        return stats.beta.ppf(u, **params)
    if name == "gamma":
        return stats.gamma.ppf(u, **params)
    if name == "lognormal":
        return stats.lognorm.ppf(u, **params)
    if name == "pareto":
        return stats.pareto.ppf(u, **params)
    if name == "weibull":
        return stats.weibull_min.ppf(u, **params)
    return stats.norm.ppf(u)


def _block_correlation(n_header, n_flow, n_behavioral, within, cross) -> np.ndarray:
    d = n_header + n_flow + n_behavioral
    groups = np.zeros(d, dtype=int)
    groups[n_header:n_header + n_flow] = 1
    groups[n_header + n_flow:] = 2
    corr = np.full((d, d), cross)
    for g in range(3):
        mask = groups == g
        corr[np.ix_(mask, mask)] = within
    np.fill_diagonal(corr, 1.0)
    corr = (corr + corr.T) / 2
    eigval, eigvec = np.linalg.eigh(corr)
    eigval = np.clip(eigval, 1e-6, None)
    return eigvec @ np.diag(eigval) @ eigvec.T


class NetworkFlowGenerator:
    """Generates labeled synthetic enterprise-network flow feature vectors."""

    def __init__(
        self,
        n_features: int = 64,
        n_header: int = 16,
        n_flow: int = 24,
        n_behavioral: int = 24,
        within_group_corr: float = 0.35,
        cross_group_corr: float = 0.10,
        seed: int = 42,
    ):
        assert n_header + n_flow + n_behavioral == n_features
        self.n_features = n_features
        self.n_header, self.n_flow, self.n_behavioral = n_header, n_flow, n_behavioral
        self._rng = np.random.default_rng(seed)
        self.marginals = _build_marginals(n_header, n_flow, n_behavioral, self._rng)
        cov = _block_correlation(n_header, n_flow, n_behavioral, within_group_corr, cross_group_corr)
        self._chol = np.linalg.cholesky(cov + 1e-8 * np.eye(n_features))
        self.attack_dims = _resolve_attack_dims(n_header, n_flow, n_behavioral)
        self._attack_shift_rng = np.random.default_rng(seed + 1)
        self._attack_shifts = {
            atk: self._attack_shift_rng.uniform(1.4, 2.6, size=len(dims))
            for atk, dims in self.attack_dims.items()
        }

    def _latent_normal(self, n: int, rng: np.random.Generator) -> np.ndarray:
        z = rng.standard_normal((n, self.n_features))
        return z @ self._chol.T

    def _to_features(self, z: np.ndarray) -> np.ndarray:
        u = stats.norm.cdf(z)
        x = np.empty_like(z)
        for j, (name, params) in enumerate(self.marginals):
            x[:, j] = _sample_marginal(name, params, u[:, j])
        return x

    def generate_normal(self, n: int, rng: np.random.Generator) -> np.ndarray:
        z = self._latent_normal(n, rng)
        return self._to_features(z)

    def generate_attack(self, n: int, attack_type: str, rng: np.random.Generator,
                         strength: float = 1.0, noise_scale: float = 0.5) -> np.ndarray:
        z = self._latent_normal(n, rng)
        dims = self.attack_dims[attack_type]
        shifts = self._attack_shifts[attack_type] * strength
        for k, j in enumerate(dims):
            z[:, j] = z[:, j] * (1.0 + 0.4 * strength) + shifts[k]
        z += noise_scale * rng.standard_normal(z.shape) * 0.15
        return self._to_features(z)

    def generate_dataset(
        self,
        n_samples: int,
        attack_ratio: float = 0.2,
        attack_types: list | None = None,
        attack_strength: float = 1.0,
        noise_scale: float = 0.5,
        random_state: int = 0,
        exclude_attack: str | None = None,
    ) -> pd.DataFrame:
        rng = np.random.default_rng(random_state)
        attack_types = attack_types or list(self.attack_dims.keys())
        if exclude_attack is not None:
            attack_types = [a for a in attack_types if a != exclude_attack]

        n_attack = int(round(n_samples * attack_ratio))
        n_normal = n_samples - n_attack
        per_type = n_attack // len(attack_types)
        remainder = n_attack - per_type * len(attack_types)

        cols = [f"f{i}" for i in range(self.n_features)]
        blocks = [self.generate_normal(n_normal, rng)]
        labels = [0] * n_normal
        atk_names = ["normal"] * n_normal

        for i, atk in enumerate(attack_types):
            n_atk = per_type + (1 if i < remainder else 0)
            if n_atk == 0:
                continue
            blocks.append(self.generate_attack(n_atk, atk, rng, attack_strength, noise_scale))
            labels += [1] * n_atk
            atk_names += [atk] * n_atk

        X = np.vstack(blocks)
        df = pd.DataFrame(X, columns=cols)
        df["label"] = labels
        df["attack_type"] = atk_names
        df = df.sample(frac=1, random_state=int(rng.integers(2**31))).reset_index(drop=True)
        return df
